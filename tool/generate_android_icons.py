#!/usr/bin/env python3
"""Generate Android launcher resources; requires Python 3 and rsvg-convert."""

from pathlib import Path
import subprocess
import xml.etree.ElementTree as ET
from xml.sax.saxutils import quoteattr


ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "android/app/src/main/res"
SOURCE = ROOT / "android/artwork/discourse_icon.svg"
# The logo's dark outer D becomes the full-bleed background, as on Meta.
# Center the visible colored speech bubble rather than the enclosing D.
PATHS = list(ET.parse(SOURCE).getroot())[1:]
SCALE = "0.74"
# Optical correction: move slightly up/right to balance the tail and color mass.
X, Y = "15.97", "14.75"
BACKGROUND = "#000000"
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n'
GENERATED = '<!-- Generated by tool/generate_android_icons.py. -->\n'


def write_resource(name, content):
    target = RES / name
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(HEADER + GENERATED + content)


def vector(paths):
    return (
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp"\n'
        '    android:viewportWidth="108" android:viewportHeight="108">\n'
        f'    <group android:translateX="{X}" android:translateY="{Y}"\n'
        f'        android:scaleX="{SCALE}" android:scaleY="{SCALE}">\n'
        + paths
        + '    </group>\n</vector>\n'
    )


def main():
    foreground = "".join(
        f'        <path android:fillColor={quoteattr(p.attrib["fill"])} '
        f'android:pathData={quoteattr(p.attrib["d"])} />\n'
        for p in PATHS
    )
    write_resource("drawable/ic_launcher_foreground.xml", vector(foreground))
    # Use the core bubble as one solid path, avoiding seams between color arcs
    # when the launcher tints the monochrome drawable.
    monochrome = (
        '        <path android:fillColor="#000000" '
        f'android:pathData={quoteattr(PATHS[0].attrib["d"])} />\n'
    )
    write_resource("drawable/ic_launcher_monochrome.xml", vector(monochrome))
    write_resource(
        "mipmap-anydpi-v26/ic_launcher.xml",
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/ic_launcher_background" />\n'
        '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
        '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
        '</adaptive-icon>\n',
    )
    write_resource(
        "values/colors.xml",
        f'<resources>\n    <color name="ic_launcher_background">{BACKGROUND}</color>\n</resources>\n',
    )

    # Pre-Android 8 launchers need a finished bitmap. Use the same visible 72dp
    # viewport as adaptive icons, with a rounded black tile and transparent rim.
    paths = "".join(ET.tostring(p, encoding="unicode") for p in PATHS)
    legacy = (
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="18 18 72 72">'
        f'<rect x="20" y="20" width="68" height="68" rx="16" fill="{BACKGROUND}"/>'
        f'<g transform="translate({X} {Y}) scale({SCALE})">{paths}</g></svg>'
    )
    for density, size in [("mdpi", 48), ("hdpi", 72), ("xhdpi", 96),
                          ("xxhdpi", 144), ("xxxhdpi", 192)]:
        target = RES / f"mipmap-{density}/ic_launcher.png"
        subprocess.run(
            ["rsvg-convert", "--width", str(size), "--height", str(size),
             "--output", str(target)],
            input=legacy.encode(), check=True,
        )


if __name__ == "__main__":
    main()
